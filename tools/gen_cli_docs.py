#!/usr/bin/env python3
"""Regenerate docs/cli.md from each script's --help (run after changing any CLI).

  python3 tools/gen_cli_docs.py           # rewrite docs/cli.md
  python3 tools/gen_cli_docs.py --check   # exit 1 if docs/cli.md is stale (CI / tests)
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "cli.md"

TOOLS = [
    ("inspect_workbook.py", [], "Audit an existing workbook. Read-only, never executes scripts."),
    ("new_connector.py", [], "Scaffold a connector (CONFIG + runtime + FETCH) with `TODO(tabext)` markers."),
    ("check_script.py", [], "Static compatibility check. See `reference/table_extension_contract.md` for every rule id."),
    ("set_secret.py", [], "Store a credential on the TabPy host. The value never reaches stdout, argv or the chat."),
    ("run_local.py", [], "Run a connector the way TabPy does and validate the output contract."),
    ("patch_workbook.py", ["replace"], "Replace the script (and optionally the column metadata) of an existing Table Extension."),
    ("patch_workbook.py", ["new"], "Create a minimal workbook containing one Table Extension data source."),
]

HEAD = """# CLI reference

<!-- generated by tools/gen_cli_docs.py - edit the scripts' argparse help, then rerun -->

All scripts live in `scripts/`. Run them with the Python that matches the
TabPy host (`python3 -I` when the input came from elsewhere). Exit codes:
`0` = OK, `1` = check errors (`check_script`, `run_local` contract
failure), `2` = refused / usage error.

Typical sequence:

```
inspect_workbook.py WB.twb            # what's there
new_connector.py ... --out c.py       # scaffold
check_script.py c.py                  # until 0 errors
set_secret.py acme.token              # user, on the TabPy host
run_local.py c.py --out out/          # or --tabpy URL
patch_workbook.py replace WB.twb --script c.py --schema out/schema.json
```
"""


def help_text(script, sub):
    r = subprocess.run([sys.executable, "-I", str(ROOT / "scripts" / script)] + sub + ["--help"],
                       capture_output=True, text=True, timeout=60, env={"COLUMNS": "100", "PATH": "/usr/bin:/bin"})
    if r.returncode != 0:
        raise SystemExit("%s %s --help failed: %s" % (script, sub, r.stderr[-300:]))
    return r.stdout.rstrip()


def render():
    parts = [HEAD]
    for script, sub, blurb in TOOLS:
        title = " ".join([script] + sub)
        parts.append("\n## `%s`\n\n%s\n\n```text\n%s\n```\n" % (title, blurb, help_text(script, sub)))
    return "".join(parts)


def _normalize(text):
    """Compare content, not argparse's version-specific layout: 'optional arguments:'
    (<= 3.9) vs 'options:', '-o OUT, --out OUT' (<= 3.12) vs '-o, --out OUT', and
    line wrapping of usage strings."""
    text = text.replace("optional arguments:", "options:")
    text = re.sub(r"(?m)(-\w) [A-Z][A-Z0-9_]*, (--)", r"\1, \2", text)
    return re.sub(r"\s+", " ", text).strip()


def main():
    text = render()
    if "--check" in sys.argv:
        ok = OUT.exists() and _normalize(OUT.read_text()) == _normalize(text)
        print("docs/cli.md is %s" % ("up to date" if ok else "STALE - run tools/gen_cli_docs.py"))
        return 0 if ok else 1
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(text)
    print("wrote %s" % OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
